const assert=require('node:assert/strict');
const path=require('node:path');
const {chromium}=require(require.resolve('playwright',{paths:[process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES||process.cwd()]}));
const app=require('../assets/dashboard/dashboard.js');
const base=process.env.DASHBOARD_TEST_URL||'http://127.0.0.1:8765/Classroom_Dashboard.html';
(async()=>{
  const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.clock.install({time:new Date('2026-11-03T12:04:59Z')});
  await page.goto(base+'?preview=1');
  await page.waitForSelector('.prompt');
  assert.match(await page.locator('#connection').textContent(),/PREVIEW/);
  assert.equal(await page.locator('.course').count(),5);
  assert.equal(await page.locator('.course.active[open]').count(),1);
  assert.equal(await page.locator('#announcement').isVisible(),false);
  await page.clock.runFor(1500);
  assert.equal(await page.locator('#announcement').isVisible(),true);
  assert.equal(await page.locator('#announcement-title').textContent(),'Focus');
  assert.equal(await page.locator('#tab-starter').getAttribute('aria-selected'),'true');
  await page.locator('#dismiss-announcement').click();
  await page.locator('#tab-brain').click();
  assert.match(await page.locator('#activity-panel').textContent(),/Look up & reset/);
  await page.locator('#tab-brain').press('ArrowRight');
  assert.equal(await page.locator('#tab-exit').getAttribute('aria-selected'),'true');
  assert.match(await page.locator('#activity-panel').textContent(),/conditional you tested/);
  await page.locator('#settings-open').click();
  await page.locator('#phase-choice').selectOption('4');
  await page.locator('#set-phase').click();
  assert.equal(await page.locator('#announcement-title').textContent(),'Cleanup');
  assert.match(await page.locator('#phase-mode').textContent(),/Manual/);
  await page.locator('#dismiss-announcement').click();
  await page.locator('#settings-open').click();await page.locator('#auto-phase').click();
  assert.equal(await page.locator('#phases [aria-current]').textContent(),'2Focus');
  await page.locator('#tab-starter').click();
  await page.screenshot({path:path.join(__dirname,'../../dashboard-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:path.join(__dirname,'../../dashboard-mobile.png'),fullPage:true});
  assert.deepEqual(errors,[]);

  const live=await browser.newPage();
  await live.clock.install({time:new Date('2026-11-03T12:00:00Z')});
  await live.addInitScript(()=>localStorage.setItem('gci.dashboard.feed','https://script.google.com/macros/s/test/exec'));
  let fail=false;
  await live.route('https://script.google.com/**',async route=>{
    if(fail)return route.abort();
    const data=app.sample(new Date('2026-11-03T12:00:00Z'));
    data.starter.prompt='<img src=x onerror=alert(1)>';
    data.requestId=new URL(route.request().url()).searchParams.get('requestId');
    await route.fulfill({contentType:'application/javascript',body:`gciDashboardFeed(${JSON.stringify(data)});`});
  });
  await live.goto(base);await live.waitForFunction(()=>document.getElementById('connection').textContent.startsWith('Connected'));
  assert.equal(await live.locator('#activity-panel img').count(),0);
  fail=true;await live.locator('#refresh').click();await live.waitForFunction(()=>document.getElementById('connection').textContent.includes('previously loaded'));
  assert.equal(await live.locator('.prompt').textContent(),'<img src=x onerror=alert(1)>');
  await browser.close();console.log('Browser checks passed: transitions, tabs, manual controls, mobile layout, feed rendering, safe text, and offline retention.');
})().catch(error=>{console.error(error);process.exit(1);});
